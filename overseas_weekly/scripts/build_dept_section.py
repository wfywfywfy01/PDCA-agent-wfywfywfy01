def make_static(src: Path) -> Path | None:
    """用 headless Chrome 执行 JS 后 dump DOM，产出不依赖 JS 的静态版"""
    if not CHROME.exists():
        print("  ! 未找到 Chrome，跳过静态版")
        return None
    r = subprocess.run(
        [str(CHROME), "--headless", "--disable-gpu", "--dump-dom",
         "--virtual-time-budget=6000", src.resolve().as_uri()],
        capture_output=True, text=True, encoding="utf-8", errors="replace")
    dom = re.sub(r"<script>.*?</script>", "", r.stdout, flags=re.S)
    dom = dom.replace("</head>", """
<style>
  /* 静态版：关闭入场动画，保证任何环境立即可见 */
  .fade,.pop{animation:none !important;opacity:1 !important;transform:none !important}
  .draw{animation:none !important;stroke-dasharray:none !important;stroke-dashoffset:0 !important}
  svg{cursor:default !important}
</style>
</head>""", 1)
    p = src.with_name(src.stem + "_static.html")
    p.write_text(dom, encoding="utf-8")
    return p




