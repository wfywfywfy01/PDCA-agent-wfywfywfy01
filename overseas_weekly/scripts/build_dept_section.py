def build_all(order, depts) -> Path:
    """把各部门章节合并成一个 HTML；标签页用 radio + CSS，无 JS 依赖。"""
    panes, scripts, rules, tabs, inputs = [], [], [], [], []
    for i, key in enumerate(order):
        if key not in depts:
            continue
        sid = SLUG[key]
        src = build(key, depts[key], pfx=f"{sid}_")      # 复用单部门生成，取其内容
        html = src.read_text(encoding="utf-8")
        body = html.split("<!--SEC-START-->", 1)[1].split("<!--SEC-END-->", 1)[0]
        js = html.split("<script>", 1)[1].split("</script>", 1)[0]
        js = "const PFX=" + js.split("const PFX=", 1)[1]      # 去掉公共函数库，只留本部门
        scripts.append("(function(){\n" + js.strip() + "\n})();")
        panes.append(f'  <section class="pane" id="pane-{sid}">\n{body}\n  </section>')
        chk = " checked" if i == 0 else ""
        inputs.append(f'<input class="tabin" type="radio" name="dept" id="tab-{sid}"{chk}>')
        tabs.append(f'<label for="tab-{sid}">{esc(NAV_LABEL[key])}</label>')
        rules.append(f"  #tab-{sid}:checked ~ .nav label[for=tab-{sid}]"
                     "{color:var(--ink);border-bottom-color:var(--ink)}")
        rules.append(f"  #tab-{sid}:checked ~ .panes > #pane-{sid}{{display:block}}")

    lib = JS_LIB  # 公共函数只放一份
    html = f"""<!doctype html>
<html lang="zh-CN">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width,initial-scale=1" />
<title>海外经销商 2026-W30 周报</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&display=swap" rel="stylesheet">
<style>{CSS}{TAB_CSS % {"rules": chr(10).join(rules)}}</style>
</head>
<body>
<div class="sheet">
{chr(10).join(inputs)}
  <div class="nav">
{chr(10).join("    " + t for t in tabs)}
    <span class="sp"></span>
    <span class="tag">2026-W30 · 07/20–07/26</span>
  </div>
  <div class="panes">
{chr(10).join(panes)}
  </div>
</div>
<script>
{lib}
{chr(10).join(scripts)}
</script>
</body>
</html>
"""
    out = OUT / "2026-W30_海外经销商周报.html"
    out.write_text(html, encoding="utf-8")
    return out


